#!/usr/bin/env python
"""Write RESULTS.md and results/final/summary.md from the result files, so that no number is typed by hand.

usage (repo root):  python research/placement/report.py
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results", "final")
MODELS = (("full", "完整模型"), ("nopair", "有注意力，不给命中间的关系"), ("mlp", "每个命中单独判断"))
SPLITS = (("test_unseen_class", "没见过的纲"), ("test_bench_lineage", "基准受体的谱系"))
GENOMES = (("spike_ecoli", "大肠杆菌"), ("spike_entamoeba", "内阿米巴"), ("transplant_legionella", "军团菌（DNA 移植）"))


def load(name):
    return json.load(open(os.path.join(R, name)))


def f(x, p="%.2f"):
    return "–" if x is None else p % x


def ci(v):
    return "%+.3f 到 %+.3f" % tuple(v)


def summary(metrics, fresh, allq, scaling, bench):
    """Every number, in English, for whoever wants to check a figure of RESULTS.md."""
    L = ["# Placement model: all numbers of the final run", "",
         "Generated by `research/placement/report.py` from the JSON files in this folder.", "",
         "## Placement accuracy", "", "| model | test set | examples | per-hit accuracy | mean over depths | nearest within one rank | node right | node depth within one rank |", "|---|---|---|---|---|---|---|---|"]
    for m, _ in MODELS:
        for sp, _ in SPLITS:
            a = metrics[m][sp]["all"]
            L.append("| %s | %s | %d | %.3f | %.3f | %.3f | %.3f | %.3f |" % (m, sp, a["n"], a["hit_acc"], a["hit_acc_macro"], a["nearest_within1"], a["node_acc"], a["node_depth_within1"]))
    for title, t in (("queries of the second search", fresh), ("all held-out queries", allq), ("all data versus a third, queries of the second search", scaling)):
        for sp, res in t["splits"].items():
            cols = list(next(iter(res["strata"].values()))["scores"])
            cols = [k for k in cols if k.endswith((".disc", ".node")) or "." not in k]
            L += ["", "## Trials, %s, %s" % (sp, title), "",
                  "%d token sets, %d source proteomes; clean natives from %d marker proteins of %d proteomes. Cells: AUROC / recall at 5%% false positives (realised rate) / recall at 1%%." % (
                      res["n_token_sets"], res["n_source_proteomes"], res["n_native_proteins"], res["n_marker_proteomes"]), "",
                  "| stratum | foreign | natives (proteins) | " + " | ".join(cols) + " |", "|---|---|---|" + "---|" * len(cols)]
            for label, row in res["strata"].items():
                L.append("| %s | %d | %d (%d) | %s |" % (label, row["n_foreign"], row["n_clean_native"], row["n_native_proteins"], " | ".join(
                    "%s / %s (%s) / %s" % (f(row["scores"][k]["auroc"], "%.3f"), f(row["scores"][k]["recall_fpr5"]), f(row["scores"][k]["realised_fpr5"], "%.3f"),
                                           f(row["scores"][k]["recall_fpr1"])) for k in cols) if row["n_foreign"] else "no trials"))
            for ref, d in res.get("minus_other_ci95", {}).items():
                L += ["", "`%s` minus other score, 95%% interval over %d held-out classes (AUROC; recall at 5%% false positives):" % (ref, res["n_classes"]), ""]
                L += ["- %s: %+.3f … %+.3f; %+.3f … %+.3f" % (k, v["auroc"][0], v["auroc"][1], v["recall_fpr5"][0], v["recall_fpr5"][1]) for k, v in d.items()]
    L += ["", "## Spike-in benchmark", "",
          "`ai`, `rules`: the pipeline. `ai_all`: its Alien Index for every gene that has one. `gbm_hits`: feature model trained on the other recipients. `rule_*`: rules on the "
          "placement model's tokens (`_pipe`: the pipeline's home group, `_tb`: ties broken by bit score, `_tok`: home = phylum, `_near`: nearest group still sampled). "
          "`place_*`: the model. `nopair_*`, `mlp_*`, `untrained_*`, `third_*`: ablations, an untrained model, the model trained on a third of the data."]
    for ds, r in bench.items():
        cm = list(r["core_matched"].items())
        L += ["", "### %s" % ds, "", "%d positives, %d core genes, %d negatives in all; the high tier lets %d negatives through at recall %.3f." % (
            r["n_pos"], r["n_core"], r["n_neg"], r["high_tier_fp"], r["high_tier_recall"]), "",
            "| score | AP vs core | AP vs all | recall at high-tier FP | recall at 1% FP | AP vs all minus rules (95%) | " + " | ".join("recall with %d core genes through" % v["core_fp"] for _, v in cm) + " |",
            "|---|---|---|---|---|---|" + "---|" * len(cm)]
        for k, s in r["scores"].items():
            c = s.get("minus_rules_ci95")
            L.append("| %s | %.3f | %.3f | %.3f | %.3f | %s | %s |" % (k, s["ap_core"], s["ap_all"], s["recall_at_high_fp"], s["recall_at_1pct_fp"],
                     "%+.3f … %+.3f" % tuple(c["ap_all"]) if c else "", " | ".join("%.3f" % v["recall"][k] for _, v in cm)))
    return "\n".join(L) + "\n"


